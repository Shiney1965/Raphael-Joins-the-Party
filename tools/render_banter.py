"""Render the banter proposal with Raphael's exact recorded words.

The proposal names each recorded line as {{handle|gist}}, where the handle is the line's id or a
prefix of it that matches exactly one line. This script looks every handle up in the
line dump extracted from the user's own game files and writes a reading copy next to the proposal.
It fails (exit 1) if any handle is not a recorded line of Raphael or of a companion whose lines were dumped.

Usage:  python tools\\render_banter.py [proposal.md]
"""
import csv
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, "_vanilla_ref", "dumps", "RAPHAEL_VOICED_LINES_611.tsv")
COMP = os.path.join(ROOT, "_vanilla_ref", "dumps", "companions")
DEFAULT = os.path.join(ROOT, "BANTER_PROPOSAL_2026-10-05.md")
TOKEN = re.compile(r"\{\{(h[0-9a-f]{8,}[0-9a-g]*)\|([^{}]*)\}\}")


def load_lines():
    rows = {}
    with open(TSV, encoding="utf-8-sig", newline="") as f:
        for i, row in enumerate(csv.reader(f, delimiter="\t", quoting=csv.QUOTE_NONE)):
            if i == 0 and row and row[0].strip().lower() == "handle":
                continue
            if len(row) < 5:
                continue
            rows[row[0].strip()] = {"handle": row[0].strip(), "len": row[1], "prio": row[2], "src": row[3],
                                    "text": row[4].strip(), "who": "RAPHAEL"}
    # Haarlep's 60 lines (same actor as Raphael; used by the private scene): handle, length_s, source_dialog, text
    hp = os.path.join(os.path.dirname(TSV), "HAARLEP_VOICED_LINES_60.tsv")
    if os.path.exists(hp):
        with open(hp, encoding="utf-8", newline="") as f:
            for i, row in enumerate(csv.reader(f, delimiter="\t", quoting=csv.QUOTE_NONE)):
                if i and len(row) >= 4:
                    rows.setdefault(row[0].strip(), {"handle": row[0].strip(), "len": row[1], "prio": "", "src": row[2],
                                                     "text": row[3].strip(), "who": "HAARLEP"})
    # companions' lines (tools\\dump_companion_lines.py): handle, length_s, priority, source_dialog, node8, text
    for path in sorted(glob.glob(os.path.join(COMP, "*_VOICED_LINES.tsv"))):
        who = os.path.basename(path).split("_")[0]
        with open(path, encoding="utf-8-sig", newline="") as f:
            for i, row in enumerate(csv.reader(f, delimiter="\t", quoting=csv.QUOTE_NONE)):
                if i == 0 or len(row) < 6:
                    continue
                h = row[0].strip()
                if h in rows:
                    # the same line is recorded by several speakers (shared origin lines); list them all
                    if who not in rows[h]["who"].split("+"):
                        rows[h]["who"] += "+" + who
                    continue
                rows[h] = {"handle": h, "len": row[1], "prio": row[2], "src": row[3], "text": row[5].strip(), "who": who}
    return rows


def resolve(lines, h):
    """A handle may be written in full or as a prefix that matches exactly one recorded line."""
    if h in lines:
        return lines[h]
    hits = [k for k in lines if k.startswith(h)]
    return lines[hits[0]] if len(hits) == 1 else None


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else DEFAULT
    lines = load_lines()
    text = open(src, encoding="utf-8").read()
    unknown, used = [], []

    def sub(m):
        h, gist = m.group(1), m.group(2)
        row = resolve(lines, h)
        if row is None:
            unknown.append((h, gist))
            return "**[UNKNOWN LINE %s: %s]**" % (h, gist)
        used.append(h)
        return "“%s”" % row["text"]

    out = TOKEN.sub(sub, text)
    leftover = re.findall(r"\{\{[^{}]*\}\}", out)
    stem = "BANTER_PROPOSAL" if os.path.abspath(src) == os.path.abspath(DEFAULT) else os.path.splitext(os.path.basename(src))[0]
    dst = os.path.join(os.path.dirname(src), stem + "_reading_copy.md")
    head = ("<!-- Generated by tools\\render_banter.py from %s. Do not edit; edit the proposal and re-run.\n"
            "     Raphael's lines are quoted from the user's own game files for private reference. -->\n\n"
            % os.path.basename(src))
    open(dst, "w", encoding="utf-8", newline="\n").write(head + out)

    # line index: every token with its source dialog and length, for checking context
    idx = os.path.join(os.path.dirname(src), stem + "_line_index.tsv")
    with open(idx, "w", encoding="utf-8", newline="\n") as f:
        f.write("speaker\thandle\tlength_s\tpriority\tsource_dialog\tgist_in_proposal\ttext\n")
        for m in TOKEN.finditer(text):
            row = resolve(lines, m.group(1))
            if row:
                f.write("\t".join([row["who"], row["handle"], row["len"], row["prio"], row["src"], m.group(2), row["text"]]) + "\n")

    print("recorded lines loaded  : %d (Raphael %d)" % (len(lines), sum(1 for r in lines.values() if r["who"] == "RAPHAEL")))
    print("tokens in proposal     : %d (%d distinct)" % (len(used) + len(unknown), len(set(used)) + len(set(h for h, _ in unknown))))
    print("unknown handles        : %d" % len(unknown))
    for h, g in unknown:
        print("   %s  %s" % (h, g))
    if leftover:
        print("malformed tokens       : %d" % len(leftover))
        for t in leftover[:20]:
            print("   " + t)
    print("reading copy           : " + dst)
    print("line index             : " + idx)
    return 1 if (unknown or leftover) else 0


if __name__ == "__main__":
    sys.exit(main())
