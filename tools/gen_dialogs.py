# ------------------------------------------------------------------ ids.json (add keys, never change existing)
def load_ids():
    return json.load(open(IDS, encoding="utf-8-sig"))


def ensure_ids(keys, write):
    ids = load_ids()
    missing = [k for k in keys if k not in ids]
    if missing and write:
        ids = load_ids()  # re-read right before writing (other tools add keys too)
        for k in missing:
            if k not in ids:
                ids[k] = str(uuid.uuid4())
        raw = open(IDS, "rb").read()
        nl = "\r\n" if b"\r\n" in raw else "\n"
        text = json.dumps(ids, indent=2).replace("\n", nl)
        if raw.endswith(b"\n"):
            text += nl
        with open(IDS, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        NOTE.append(f"ids.json: added {', '.join(missing)}")
    elif missing:
        err(f"ids.json lacks {missing} (run without --check once)")
    return ids


# ------------------------------------------------------------------ vanilla lookups
def vanilla_loca():
    t = open(os.path.join(REF, "english.xml"), encoding="utf-8-sig").read()
    return {m.group(1): (int(m.group(2)), html.unescape(m.group(3)))
            for m in re.finditer(r'contentuid="([^"]+)" version="(\d+)">(.*?)</content>', t, re.S)}


def vanilla_dialog_versions():
    """handle -> set of TagText versions used in the vanilla Raphael dialogs (_vanilla_ref/dialogs)"""
    out = {}
    for f in glob.glob(os.path.join(REF, "dialogs", "**", "*.lsj"), recursive=True):
        for m in re.finditer(r'"handle":\s*"(h[0-9a-g]+)",\s*"type":\s*"TranslatedString",\s*"version":\s*(\d+)',
                             open(f, encoding="utf-8-sig").read()):
            out.setdefault(m.group(1), set()).add(int(m.group(2)))
    return out


