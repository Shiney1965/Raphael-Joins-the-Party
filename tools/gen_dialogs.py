def origin_lines(name):
    """handle -> recorded length for one origin companion (tools/dump_companion_lines.py)"""
    if name not in _ORIGIN_LINES:
        rows = {}
        p = os.path.join(DUMPS, "companions", name + "_VOICED_LINES.tsv")
