def slots_of(spec, dlg, slot0_override=None):
    """speaker slots of a dialog: [{"list": GUID, "role": "raphael" | "players" | "origin:<NAME>"}]"""
    if dlg.get("slots"):
        return dlg["slots"]
    route = slot0_override or (spec["slot0_route"] if dlg["slot0"] == "route" else dlg["slot0"])
    out = [{"list": spec["slot0_lists"][route], "role": "raphael"}]
    if not dlg["automated"]:
        out.append({"list": spec["group_players"], "role": "players"})
    return out


def expand_spec(spec):
    """appends the one-line bark ADs and the two-speaker banter ADs listed in src/banter_content.json"""
    if not os.path.exists(BANTER):
        err("src/banter_content.json is missing (run tools/gen_banter_content.py)")
        return
    content = json.load(open(BANTER, encoding="utf-8"))
    comp = spec["slot0_lists"]["companion"]
    for bk in content["barks"]:
        spec["dialogs"].append({
            "name": bk["name"], "ids": "DLG_" + bk["name"][len("RJTP_AD_"):].upper(), "subpath": "RJTP_Barks",
            "automated": True, "timeline_id": "", "block_ftb": False, "category": "Automated NPC Dialog",
            "slots": [{"list": comp, "role": "raphael"}], "require_unconditional_root": True,
            "synopsis": "Solo bark of the RJTP companion, group %s. One line, no timeline (the shape proven by the "
                        "voice tests). Started by RJTP_Banter.txt." % bk["group"],
            "how_to_trigger": "PROC_RJTP_Bark(%s) or the test spell Shout_RJTP_Debug_Bark." % bk["group"],
            "roots": ["r_line"], "nodes": {"r_line": {"type": "TagGreeting", "speaker": 0, "line": bk["line"], "end": True}},
            "_bark": bk})
    for bt in content["banters"]:
        origin_first = bt["lines"][0]["speaker"] == 1
        raphael = {"list": comp, "role": "raphael"}
        origin = {"list": bt["origin"], "role": "origin:" + bt["companion"]}
        slots = [origin, raphael] if origin_first else [raphael, origin]
        nodes = {}
        for i, ln in enumerate(bt["lines"], 1):
            is_origin = ln["speaker"] == 1
            n = {"type": "TagGreeting" if i == 1 else "TagAnswer",
                 "speaker": (0 if is_origin == origin_first else 1), "line": ln["line"]}
            if i == len(bt["lines"]):
                n["end"] = True
            else:
                n["children"] = ["l%d" % (i + 1)]
            nodes["l%d" % i] = n
        spec["dialogs"].append({
            "name": bt["name"], "ids": "DLG_" + bt["name"][len("RJTP_"):].upper(), "subpath": "RJTP_Banter",
            "automated": True, "timeline_id": "", "block_ftb": False, "category": "Voice bark",
            "slots": slots, "require_unconditional_root": True,
            "synopsis": "Two-sided banter with %s (%s). Every line is an existing recording. No timeline (experiment)."
                        % (bt["companion"].capitalize(), bt["title"]),
            "how_to_trigger": "Test spell Shout_RJTP_Debug_Banter, or the engine's party banter (Gossips.lsx) once "
                              "the global flag RJTP_Banter_Enabled is set.",
            "roots": ["l1"], "nodes": nodes, "_banter": bt, "_origin_first": origin_first})
    if os.path.exists(DONOR_MAP):
        dm = json.load(open(DONOR_MAP, encoding="utf-8"))
        for dlg in spec["dialogs"]:
            if dlg["name"] in dm:
                dlg["_donor"] = dm[dlg["name"]]
    for dlg in spec["dialogs"]:
        if dlg.get("needs_donor_timeline") and "_donor" not in dlg:
            err("%s: no entry in src/timeline_donor_map.json (run tools/gen_timelines.py first)" % dlg["name"])


_OTHER_VOICE = {}


def other_voice_lines(name):
    """handle -> recorded length for a non-Raphael voice Raphael may borrow (Haarlep: same actor, own speaker id)"""
    if name not in _OTHER_VOICE:
        rows = {}
        p = os.path.join(DUMPS, {"HAARLEP": "HAARLEP_VOICED_LINES_60.tsv"}[name])
        for i, ln in enumerate(open(p, encoding="utf-8")):
            c = ln.rstrip("\n").split("\t")
            if i and len(c) >= 2:
                rows[c[0]] = float(c[1] or 0)
        _OTHER_VOICE[name] = rows
    return _OTHER_VOICE[name]


