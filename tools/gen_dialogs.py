def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def divine(src, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    r = subprocess.run([DIVINE, "-g", "bg3", "-a", "convert-resource", "-s", src, "-d", dst],
                       capture_output=True, text=True)
    if r.returncode or not os.path.exists(dst):
        err(f"Divine failed {src} -> {dst}: {r.stdout.strip()} {r.stderr.strip()}")
        return False
    return True


def strip_time(d):
    d = copy.deepcopy(d)
    d["save"]["header"].pop("time", None)
    d["save"]["header"].pop("version", None)
    return d


def roundtrip(lsj_path, lsf_path):
    tmp = tempfile.mkdtemp(prefix="rjtp_rt_")
    back = os.path.join(tmp, "back.lsj")
    if not divine(lsf_path, back):
        return
    a = strip_time(json.load(open(lsj_path, encoding="utf-8-sig")))
    c = strip_time(json.load(open(back, encoding="utf-8-sig")))
    if json.dumps(a, sort_keys=True) != json.dumps(c, sort_keys=True):
        err(f"round-trip differs: {lsj_path}")
    else:
        NOTE.append(f"round-trip OK: {os.path.basename(lsj_path)}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--toolkit-export")
    ap.add_argument("--folder")
    ap.add_argument("--slot0", choices=["companion", "group", "monitor"])
    a = ap.parse_args()
    write_mode = not a.check
    spec = json.load(open(SPEC, encoding="utf-8"))
    if not os.path.exists(RESERVED):
        err("src/reserved_lines.json is missing (the list of lines the mod must never use)")
        return finish()
    spec["_reserved"] = {r["handle"]: r["what"] for r in json.load(open(RESERVED, encoding="utf-8"))["lines"]}
    expand_spec(spec)
    if ERR:
        return finish()
    keys = []
    for dlg in spec["dialogs"]:
        keys += [dlg["ids"] + s for s in ("_BANK", "_UUID")]
        keys += [dlg["ids"] + "_SPK%d" % i for i in range(len(slots_of(spec, dlg)))]
        if dlg.get("_banter"):
            keys.append("GOSSIP_" + dlg["ids"][len("DLG_"):])
    keys += [f["key"] for f in spec["flags"]]
    ids = ensure_ids(keys, write_mode and not a.toolkit_export)
    if ERR:
        return finish()
    mod_folder = "RaphaelJoinsTheParty_" + ids["MOD"]
    folder = a.folder or mod_folder
    root = a.toolkit_export or SRC
    MODS = os.path.join(root, "Mods", folder)
    PUB = os.path.join(root, "Public", folder)
    vloca, vver = vanilla_loca(), vanilla_dialog_versions()
    bank_keys = rekeyed_bank_keys(ids)
    vguid = vanilla_guid_names()
    loca_rows, slot_counts, built = [], {}, []
    for dlg in spec["dialogs"]:
        over = a.slot0 if (a.slot0 and dlg["slot0"] == "route") else None
        doc, nslots = build_dialog(spec, dlg, ids, vloca, vver, bank_keys, vguid, loca_rows, over)
        slot_counts[dlg["name"]] = nslots
        built.append((dlg, doc))
    # new loca must not collide with vanilla
    for r in loca_rows:
        if r["contentuid"] in vloca:
            err(f"new handle {r['contentuid']} collides with vanilla")
    # flag files: must exist (or be written) with the declared name
    for f in spec["flags"]:
        p = os.path.join(SRC, "Public", mod_folder, "Flags", ids[f["key"]] + ".lsx")
        if write_mode and not a.toolkit_export:
            write(p, flag_lsx(ids[f["key"]], f["name"], f["usage"], f["desc"]))
        elif not os.path.exists(p):
            err(f"flag file missing: {p}")
    if ERR:
        return finish()
    if not write_mode:
        return finish()
    for dlg, doc in built:
        lsj = os.path.join(MODS, "Story", "Dialogs", dlg["subpath"], dlg["name"] + ".lsj")
        write(lsj, json.dumps(doc, indent="\t", ensure_ascii=False) + "\n")
        if not a.toolkit_export:
            lsf = os.path.join(MODS, "Story", "DialogsBinary", dlg["subpath"], dlg["name"] + ".lsf")
            if divine(lsj, lsf):
                roundtrip(lsj, lsf)
    write(os.path.join(PUB, BANK_SUB), bank_lsx(spec, ids, folder, slot_counts))
    if not a.toolkit_export:
        # the bank must convert too (the build converts Content/**.lsx -> .lsf); verify in a temp folder
        tmp = tempfile.mkdtemp(prefix="rjtp_bank_")
        lsf = os.path.join(tmp, "bank.lsf")
        if divine(os.path.join(PUB, BANK_SUB), lsf) and divine(lsf, os.path.join(tmp, "bank_back.lsx")):
            back = open(os.path.join(tmp, "bank_back.lsx"), encoding="utf-8-sig").read()
            for dlg in spec["dialogs"]:
                if ids[dlg["ids"] + "_BANK"] not in back:
                    err(f"bank round-trip lost {dlg['name']}")
            for cr in {c for d in spec["dialogs"] for c in d.get("child_resources", [])}:
                if spec["vanilla_dialogs"][cr] not in back:
                    err(f"bank round-trip changed childResources GUID {cr}")
            NOTE.append("DialogBank .lsx -> .lsf -> .lsx OK (IDs and childResources GUIDs unchanged)")
        write_gossips(spec, ids, PUB)
        write_osiris_block(spec, ids, os.path.join(MODS, "Story", "RawFiles", "Goals", "RJTP_Banter.txt"))
        seen, rows = set(), []
        for r in loca_rows:
            if r["contentuid"] not in seen:
                seen.add(r["contentuid"])
                rows.append(r)
        write(LOCA_OUT, json.dumps(rows, indent=1, ensure_ascii=False) + "\n")
        NOTE.append(f"dialog_loca.json: {len(rows)} entries")
    return finish()


def write_gossips(spec, ids, pub):
    """Public/<mod>/Gossips/Gossips.lsx: one PartyBanter row per two-sided banter, as vanilla registers its own.
    DialogUUID = the DialogBank ID (347 of 349 vanilla rows). Every row is gated on the global flag
    RJTP_Banter_Enabled (all 349 vanilla rows carry ConditionFlags), which RJTP_Banter.txt sets only while he is in
    the active party and only after a banter has been seen to play (review of the v0.3a plan, B1)."""
    rows = []
    for dlg in spec["dialogs"]:
        if not dlg.get("_banter"):
            continue
        rows.append(f"""                <node id="Gossip">
                    <attribute id="DialogUUID" type="guid" value="{ids[dlg['ids'] + '_BANK']}"/>
                    <attribute id="Name" type="FixedString" value="{dlg['name']}"/>
                    <attribute id="Priority" type="int32" value="50"/>
                    <attribute id="Type" type="FixedString" value="PartyBanter"/>
                    <attribute id="UUID" type="guid" value="{ids['GOSSIP_' + dlg['ids'][len('DLG_'):]]}"/>
                    <children>
                        <node id="ConditionFlags">
                            <children>
                                <node id="Flag">
                                    <attribute id="UUID" type="guid" value="{ids['FLAG_Banter_Enabled']}"/>
                                </node>
                            </children>
                        </node>
                    </children>
                </node>
""")
    write(os.path.join(pub, "Gossips", "Gossips.lsx"),
          '<?xml version="1.0" encoding="UTF-8"?>\n<save>\n    <version major="4" minor="0" revision="9" build="331"/>\n'
          '    <region id="Gossips">\n        <node id="root">\n            <children>\n' + "".join(rows)
          + '            </children>\n        </node>\n    </region>\n</save>\n')
    NOTE.append(f"Gossips.lsx: {len(rows)} PartyBanter rows")


def write_osiris_block(spec, ids, goal_path):
    """rewrites the generated INIT facts of RJTP_Banter.txt (dialog resources carry ids.json GUIDs)"""
    lines, counts, n_all, n_banter = [], {}, 0, 0
    for dlg in spec["dialogs"]:
        res = f"(DIALOGRESOURCE){dlg['name']}_{ids[dlg['ids'] + '_BANK']}"
        if dlg.get("_bark"):
            bk = dlg["_bark"]
            n_all += 1
            counts[bk["group"]] = max(counts.get(bk["group"], 0), bk["index"])
            lines.append(f'DB_RJTP_Bark("{bk["group"]}", {bk["index"]}, {res});')
            lines.append(f'DB_RJTP_BarkAll({n_all}, "{bk["group"]}", {res});')
            if bk["group"] == "Downed":
                # vanilla stops an AD whose speaker is a downed player unless the dialog is listed here
                # (Shared __AAA_FirstGoal.txt:258-273)
                lines.append(f"DB_DialogStarted_IgnoreStopConditions({res});")
        elif dlg.get("_banter"):
            bt = dlg["_banter"]
            n_banter += 1
            who = f'(CHARACTER){ORIGIN_NAMES[bt["companion"]]}_{bt["origin"]}'
            lines.append(f'DB_RJTP_Banter({n_banter}, {res}, {who}, {1 if dlg["_origin_first"] else 0});')
    for grp, n in counts.items():
        lines.append(f'DB_RJTP_BarkCount("{grp}", {n});')
    lines.append(f"DB_RJTP_BarkAllCount({n_all});")
    lines.append(f"DB_RJTP_BanterCount({n_banter});")
    lines.append(f"DB_RJTP_BanterFlag((FLAG)RJTP_Banter_Enabled_{ids['FLAG_Banter_Enabled']});")
    if write_goal_block(goal_path, lines):
        NOTE.append(f"RJTP_Banter.txt: {n_all} bark rows, {n_banter} banter rows")
    # the private scene (new goal in v0.3b, so its INIT runs on saves that already hold RJTP_Banter)
    after = next((d for d in spec["dialogs"] if d["name"] == "RJTP_AD_PrivateAfter"), None)
    if after:
        priv = [f"DB_RJTP_PrivateFlag((FLAG)RJTP_Event_Private_{ids['FLAG_Event_Private']});",
                f"DB_RJTP_PrivateDoneFlag((FLAG)RJTP_State_Romanced_{ids['FLAG_State_Romanced']});",
                f"DB_RJTP_PrivateAfterAD((DIALOGRESOURCE){after['name']}_{ids[after['ids'] + '_BANK']});"]
        if write_goal_block(os.path.join(os.path.dirname(goal_path), "RJTP_Private.txt"), priv):
            NOTE.append("RJTP_Private.txt: 3 generated rows")


def write_goal_block(goal_path, lines):
    """replaces the text between the generated-block markers of one goal file; True on success"""
    name = os.path.basename(goal_path)
    if not os.path.exists(goal_path):
        err(f"{goal_path} does not exist")
        return False
    raw = open(goal_path, "rb").read().decode("utf-8")
    nl = "\r\n" if "\r\n" in raw else "\n"
    if raw.count(GEN_BEGIN) != 1 or raw.count(GEN_END) != 1:
        err(f"{name}: the generated-block markers must each appear exactly once")
        return False
    a = raw.index(GEN_BEGIN) + len(GEN_BEGIN)
    z = raw.index(GEN_END)
    new = raw[:a] + nl + nl.join(lines) + nl + raw[z:]
    if new != raw:
        with open(goal_path, "w", encoding="utf-8", newline="") as f:
            f.write(new)
    return True


def finish():
    for n in NOTE:
        print("  " + n)
    for e in ERR:
        print("  ERROR " + e)
    print(f"gen_dialogs: {len(ERR)} error(s)")
    sys.exit(1 if ERR else 0)


if __name__ == "__main__":
    main()
